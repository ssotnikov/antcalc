"""Derive the system splash vector from the launcher foreground using only the standard library."""
from copy import deepcopy
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
DRAWABLES = ROOT / "app/src/main/res/drawable"
ANDROID = "http://schemas.android.com/apk/res/android"
ET.register_namespace("android", ANDROID)


def android(**attributes):
    return {f"{{{ANDROID}}}{key}": value for key, value in attributes.items()}


def render():
    foreground = ET.parse(DRAWABLES / "ic_launcher_foreground.xml").getroot()
    vector = ET.Element("vector", foreground.attrib)
    # Match the no-background splash slot so Android need not upscale a 108 dp raster cache.
    vector.attrib.update(android(width="288dp", height="288dp"))
    # The rounded square fits inside the system's central 2/3 circular mask.
    ET.SubElement(vector, "path", android(
        fillColor="@color/launcher_background",
        pathData="M38,26H70Q82,26 82,38V70Q82,82 70,82H38Q26,82 26,70V38Q26,26 38,26Z",
    ))
    artwork = ET.SubElement(vector, "group", android(
        scaleX="0.8", scaleY="0.8", translateX="10.8", translateY="10.8",
    ))
    artwork.extend(deepcopy(list(foreground)))
    ET.indent(vector, space="    ")
    output = ET.tostring(vector, encoding="unicode")
    (DRAWABLES / "ic_splash.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tools/render_splash_icon.py from ic_launcher_foreground.xml. -->\n'
        + output + "\n", encoding="utf-8",
    )


if __name__ == "__main__":
    render()
